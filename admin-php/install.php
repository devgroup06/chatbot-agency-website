<?php if ($done): ?>
  <div class="login-card">
    <h1>Setup complete</h1>
    <p class="login-sub">Your admin account is ready. Log in with the email and password you just chose.</p>
    <?php if (!$publishing): ?>
      <p class="login-sub">Publishing is not connected yet, so saves will not reach the live site. Connect it
      any time from <strong>Account → Publishing</strong> inside the panel.</p>
    <?php endif; ?>
    <a class="btn" href="index.php">Go to the admin panel</a>
    <p class="hint" style="margin-top:1rem">For safety, delete <code>install.php</code> from the server now.</p>
  </div>
<?php else: ?>
  <form class="login-card wide" method="post">
    <h1>Set up DialogHive Admin</h1>
    <p class="login-sub">One-time setup. Everything you enter is stored on your own server.</p>

    <?php if ($error): ?><div class="alert bad"><?= e($error) ?></div><?php endif; ?>

    <h2 class="setup-head">1 · Database <span class="hint">— create one in hPanel → Databases → MySQL</span></h2>
    <label>Database host</label>
    <input type="text" name="db_host" value="<?= e($_POST['db_host'] ?? 'localhost') ?>" required>
    <label>Database name</label>
    <input type="text" name="db_name" value="<?= e($_POST['db_name'] ?? '') ?>" required placeholder="u504688092_dialoghive">
    <label>Database user</label>
    <input type="text" name="db_user" value="<?= e($_POST['db_user'] ?? '') ?>" required placeholder="u504688092_admin">
    <label>Database password</label>
    <input type="password" name="db_pass" required>

    <h2 class="setup-head">2 · Your admin login</h2>
    <label>Your name</label>
    <input type="text" name="name" value="<?= e($_POST['name'] ?? '') ?>" placeholder="Usman">
    <label>Email <span class="hint">— you will log in with this</span></label>
    <input type="email" name="email" value="<?= e($_POST['email'] ?? '') ?>" required>
    <label>Password <span class="hint">— at least 8 characters</span></label>
    <input type="password" name="password" required>

    <details class="setup-optional"<?= !empty($_POST['gh_token']) ? ' open' : '' ?>>
      <summary><span class="setup-head">3 · Publishing <span class="hint">— optional, you can do this later</span></span></summary>
      <p class="hint">Skip this to finish setup now. Until publishing is connected the panel works normally,
      but saves will not reach the live site. You can connect it any time from <strong>Account → Publishing</strong>.</p>
      <label>GitHub token</label>
      <input type="password" name="gh_token" placeholder="ghp_…" autocomplete="off">
